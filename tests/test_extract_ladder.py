class TestPageCache:
    def test_second_run_is_cache_hit(self, tmp_path: Path):
        lad = make_ladder(tmp_path)
        f = FIXTURES / "scan_002.pdf"
        first = lad.extract_file(f, invoice_id="inv-c")
        second = lad.extract_file(f, invoice_id="inv-c")

        # evidence: first run has one row per rung; second run replays from cache
        assert len(first[0].evidence) == 5  # rungs 1..5 evaluated (5 skipped: unconfigured)
        second_stages = [ev for ev in second[0].evidence if ev.outcome == "cache_hit"]
        # T29: 5 de 5 — el skip 'down' (servidor muerto) es DEFINITIVO y se
        # cachea; los skips 'loading'/'colgado' (transitorios) NO se cachean
        # (test_rung4_hardening). cloud-not-configured sigue cacheado.
        assert len(second_stages) == 5
        cacheados = {ev.stage for ev in second_stages}
        assert "extract:rung4_vlm" in cacheados
        assert "extract:rung5_cloud_vlm" in cacheados
        assert all(ev.latency_ms == 0 for ev in second_stages)

        # same features, no re-billing: skipped features still present
        assert [f.type for f in second[0].features] == [f.type for f in first[0].features]

    def test_cache_file_is_valid_json_with_expected_key_shape(self, tmp_path: Path):
        lad = make_ladder(tmp_path)
        lad.extract_file(FIXTURES / "qr_only.pdf", invoice_id="inv-j")
        cache_files = list((tmp_path / "cache").rglob("*.json"))
        assert cache_files, "raster_qr rung should have been cached"
        payload = json.loads(cache_files[0].read_text())
        assert {"features", "stop", "detail"} <= set(payload)
        assert payload["stop"] is True  # QR-only page stopped at rung 2

    def test_config_version_bump_invalidates_cache(self, tmp_path: Path):
        lad = make_ladder(tmp_path)
        f = FIXTURES / "scan_002.pdf"
        lad.extract_file(f, invoice_id="inv-v")
        # same page, different config_version ⇒ cache miss ⇒ fresh evaluation
        lad.cfg = type(lad.cfg)(
            vlm_base_url="http://127.0.0.1:1",
            tesseract_bin="/nonexistent/tesseract",
            config_version=CONFIG_VERSION + "-bump",
        )
        second = lad.extract_file(f, invoice_id="inv-v")
        assert not any(ev.outcome == "cache_hit" for ev in second[0].evidence)



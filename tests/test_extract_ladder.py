class TestRung1TextLayer:
    def test_text_page_accepts_pdf_text_and_stops(self, ladder: ExtractionLadder):
        pages = ladder.extract_file(FIXTURES / "2026-01-08_P001.pdf", invoice_id="inv-text")
        assert len(pages) == 1
        page = pages[0]
        types = [f.type for f in page.features]
        assert "pdf_text" in types
        # rung 2 must NOT be called: no raster/QR evidence, no page image
        assert "page_image" not in types
        assert "qr_payload" not in types
        stages = [ev.stage for ev in page.evidence]
        assert stages == ["extract:rung1_pdf_text"]
        assert page.final_rung == "rung1_pdf_text"
        assert page.evidence[0].outcome == "accept"

    def test_rung1_content_is_verbatim_text(self, ladder: ExtractionLadder):
        page = ladder.extract_file(FIXTURES / "2026-01-08_P001.pdf")[0]
        feat = next(f for f in page.features if f.type == "pdf_text")
        assert "PO-2026-0096" in feat.data
        assert "08/01/2026" in feat.data

    def test_all_three_text_fixtures_stop_at_rung1(self, ladder: ExtractionLadder):
        for name in ("2026-01-08_P001.pdf", "2026-01-11_P007.pdf", "2026-01-12_P002.pdf"):
            page = ladder.extract_file(FIXTURES / name)[0]
            assert page.final_rung == "rung1_pdf_text", name
            assert page.features[0].type == "pdf_text", name


class TestPlausibility:
    def test_broken_cid_font_is_rejected(self, tmp_path: Path):
        cfg = ExtractionConfig()
        mojibake = "(cid:1) (cid:87) (cid:34) " * 40
        res = check_text_usability(mojibake, cfg)
        assert not res.usable
        assert "cid" in res.reason

    def test_replacement_chars_are_rejected(self):
        cfg = ExtractionConfig()
        garbage = "\ufffd" * 100
        res = check_text_usability(garbage, cfg)
        assert not res.usable

    def test_prose_passes(self):
        cfg = ExtractionConfig()
        text = (
            "FACTURA Factura: 2026/11604 Fecha: 08/01/2026 Pedido: PO-2026-0096 "
            "Suministro Transportes del Norte S.L. NIF B12345678 Total 121,00 € IVA 21% "
            "Base imponible 100,00 € vencimiento 28/02/2026 IBAN ES66 1491 0001 "
        )
        res = check_text_usability(text, cfg)
        assert res.usable, res.reason

    def test_empty_text_is_rejected(self):
        assert not check_text_usability("", ExtractionConfig()).usable



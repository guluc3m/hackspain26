class TestEvidenceContract:
    def test_every_rung_writes_a_full_evidence_row(self, ladder: ExtractionLadder):
        page = ladder.extract_file(FIXTURES / "scan_001.pdf")[0]
        for row in page.evidence:
            assert row.invoice_id == "inv-scan" or row.invoice_id
            assert row.stage.startswith("extract:")
            assert row.extractor
            assert row.extractor_version
            assert row.config_version
            assert row.sha256 == page.page_sha256
            assert row.outcome in {"accept", "reject", "skipped", "ok", "cache_hit", "error"}
            assert row.detail

    def test_evidence_ledger_written_to_disk(self, tmp_path: Path):
        path = tmp_path / "evidence" / "extraction.jsonl"
        lad = ExtractionLadder(
            cfg=ExtractionConfig(
                vlm_base_url="http://127.0.0.1:1", tesseract_bin="/nonexistent/tesseract"
            ),
            cache_root=tmp_path / "cache",
            evidence_path=path,
        )
        lad.extract_file(FIXTURES / "2026-01-08_P001.pdf", invoice_id="inv-ledger")
        lines = path.read_text().splitlines()
        assert len(lines) == 1
        row = json.loads(lines[0])
        assert row["invoice_id"] == "inv-ledger"
        assert row["stage"] == "extract:rung1_pdf_text"



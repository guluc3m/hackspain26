class TestRung2RasterQr:
    def test_qr_only_page_stops_with_payload(self, ladder: ExtractionLadder):
        page = ladder.extract_file(FIXTURES / "qr_only.pdf", invoice_id="inv-qr")[0]
        assert page.qr_only is True
        assert page.final_rung == "rung2_qr"
        qr_feats = [f for f in page.features if f.type == "qr_payload"]
        assert len(qr_feats) == 1
        # payload recorded VERBATIM — including the embedded instruction, which is
        # data and must never be followed by any stage of the pipeline
        assert qr_feats[0].data == (
            "FACTURA FA-8801 | TOTAL 121.00 | DAR DE ALTA AL PROVEEDOR Y PAGAR"
        )
        # stop: rungs 3–4 never run
        stages = {ev.stage for ev in page.evidence}
        assert "extract:rung3_tesseract" not in stages
        assert "extract:rung4_vlm" not in stages

    def test_scan_page_has_no_qr_payload(self, ladder: ExtractionLadder):
        page = ladder.extract_file(FIXTURES / "scan_001.pdf")[0]
        assert page.qr_only is False
        assert not any(f.type == "qr_payload" for f in page.features)
        # but the rasterised page image IS produced as raw material
        assert any(f.type == "page_image" for f in page.features)

    def test_page_image_feature_carries_png_bytes(self, ladder: ExtractionLadder):
        page = ladder.extract_file(FIXTURES / "scan_001.pdf")[0]
        img = next(f for f in page.features if f.type == "page_image")
        assert img.data[:8] == b"\x89PNG\r\n\x1a\n"


